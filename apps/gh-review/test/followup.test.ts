import { expect, test } from 'bun:test';
// @ts-ignore plain JS module shared with the page
import { deferredWork, followUpDraft, followUpTitle, threadDefers } from '../public/followup.js';

const thread = [
  { id: 1, user: 'Dutchgoose', body: 'hmm, kind of against the spirit of the interrupts. fine for now, but ideally we should break out a tool that "adds connector to app" (and maybe same tool for agents) that uses a real interrupt. but fine to go out with' },
  { id: 2, user: 'n8agrin', body: 'Claude says: agreed. A tool built on a real interrupt is the right follow-up once that framework lands.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' },
];

test('spots comments that put work off for later', () => {
  expect(deferredWork(thread[0].body)).toBe('fine for now');
  expect(deferredWork("Let's do this in a separate PR")).toBe('in a separate PR');
  expect(deferredWork('Can we revisit this later?')).toBe('revisit this later');
  expect(deferredWork('TODO: cache this')).toBe('TODO');
  expect(threadDefers(thread)).toEqual({ id: 1, cue: 'fine for now' });
});

test('leaves ordinary review comments alone', () => {
  for (const s of ['LGTM', 'nit: rename this', 'This breaks when the list is empty.', 'eventually the loop exits', 'see `followUp()`', '> fine for now\n\nwhy?']) expect(deferredWork(s)).toBeNull();
  expect(threadDefers([{ id: 3, body: 'Looks good' }])).toBeNull();
});

test('titles the issue from the sentence that names the work', () => {
  expect(followUpTitle(thread, 'x')).toBe('Break out a tool that "adds connector to app" that uses a real interrupt');
  expect(followUpTitle([{ body: 'We should probably cache the token lookup, but later.' }], 'x')).toBe('Cache the token lookup, but later');
  expect(followUpTitle([{ body: 'ok' }], 'Follow-up from #9')).toBe('Follow-up from #9');
  expect(followUpTitle([{ body: `Ideally ${'word '.repeat(40)}` }], 'x').length).toBeLessThanOrEqual(110);
});

test('the body links back and quotes the thread without tool footers', () => {
  const { title, body } = followUpDraft({ number: 12, title: 'Ask before adding connectors' }, { comments: thread, path: 'src/agent.ts', line: 359, url: 'https://github.com/o/r/pull/12#discussion_r1' });
  expect(title).toStartWith('Break out a tool');
  expect(body).toStartWith('Follow-up from #12 (Ask before adding connectors), from [this thread](https://github.com/o/r/pull/12#discussion_r1) on `src/agent.ts:359`.');
  expect(body).toContain('> **@Dutchgoose:** hmm');
  expect(body).toContain('>\n> **@n8agrin:** Claude says: agreed.');
  expect(body).not.toContain('Generated by');
  expect(body).not.toContain('---');
});

test('a conversation comment has no file to name', () => {
  const { body } = followUpDraft({ number: 4, title: 'T' }, { comments: [{ user: 'a', body: 'line one\nline two, follow-up later' }], path: null, line: null, url: 'https://github.com/o/r/pull/4#issuecomment-1' });
  expect(body).toBe('Follow-up from #4 (T), from [this thread](https://github.com/o/r/pull/4#issuecomment-1).\n\n> **@a:** line one\n> line two, follow-up later');
});

test('a long title stops at a whole word, not on a dangling "before"', () => {
  const t = followUpTitle([{ body: `We should ${'move the thing '.repeat(7)}before shipping the rest of it.` }], 'x');
  expect(t.length).toBeLessThanOrEqual(110);
  expect(t).toMatch(/thing$/);
});
